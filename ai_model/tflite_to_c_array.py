"""
Convert TFLite model binary (.tflite) to C/C++ array (.h / .cc)
Định dạng tương thích 100% với TensorFlow Lite for Microcontrollers (TFLM) trên ESP32.
"""

import sys
import os


def convert_tflite_to_c_array(tflite_path, output_header_path, array_name="g_parking_model_data"):
    """
    Đọc file nhị phân TFLite và xuất ra file header C chứa mảng byte tĩnh.
    """
    if not os.path.exists(tflite_path):
        raise FileNotFoundError(f"Không tìm thấy file: {tflite_path}")
        
    with open(tflite_path, "rb") as f:
        bytes_data = f.read()
        
    size_bytes = len(bytes_data)
    size_kb = size_bytes / 1024.0
    
    print(f"[CONVERT] Đang chuyển đổi {tflite_path} ({size_bytes} bytes ~ {size_kb:.2f} KB)...")

    header_content = []
    header_content.append("// ==========================================================================")
    header_content.append("// AUTOGENERATED TFLITE MICRO MODEL C ARRAY")
    header_content.append(f"// File nguồn: {os.path.basename(tflite_path)}")
    header_content.append(f"// Kích thước mô hình: {size_bytes} bytes ({size_kb:.2f} KB)")
    header_content.append("// Kiến trúc: Ultra-Lightweight Depthwise Separable CNN (64x64x1)")
    header_content.append("// Định dạng: Lượng tử hóa toàn phần INT8 (Full Integer Quantization)")
    header_content.append("// ==========================================================================\n")
    header_content.append("#ifndef PARKING_MODEL_DATA_H_")
    header_content.append("#define PARKING_MODEL_DATA_H_\n")
    header_content.append("#include <stdint.h>\n")
    header_content.append(f"// Độ dài mảng dữ liệu mô hình")
    header_content.append(f"const unsigned int {array_name}_len = {size_bytes};\n")
    header_content.append(f"// Căn lề 16-byte cho vi điều khiển 32-bit ESP32")
    header_content.append(f"alignas(16) const unsigned char {array_name}[] = {{")
    
    # Định dạng 12 byte trên một dòng
    bytes_per_line = 12
    for i in range(0, size_bytes, bytes_per_line):
        chunk = bytes_data[i:i + bytes_per_line]
        hex_str = ", ".join([f"0x{b:02x}" for b in chunk])
        if i + bytes_per_line < size_bytes:
            hex_str += ","
        header_content.append(f"  {hex_str}")
        
    header_content.append("};\n")
    header_content.append(f"#endif // PARKING_MODEL_DATA_H_\n")
    
    with open(output_header_path, "w", encoding="utf-8") as f:
        f.write("\n".join(header_content))
        
    print(f"[SUCCESS] Đã ghi ra file C array: {output_header_path}")
    print(f" -> Kích thước mảng: {size_kb:.2f} KB (Đạt chuẩn < 25KB cho ESP32-CAM)")
    return size_bytes


if __name__ == "__main__":
    if len(sys.argv) > 2:
        convert_tflite_to_c_array(sys.argv[1], sys.argv[2])
    else:
        print("Sử dụng: python tflite_to_c_array.py <input.tflite> <output_model_data.h>")
